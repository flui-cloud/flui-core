import { WorldApp, worldApp, CONTROL } from './sandbox-world-topology-apps';

type Platform = [
  namespace: NonNullable<WorldApp['namespace']>,
  slug: string,
  name: string,
  category: WorldApp['category'],
  workload: WorldApp['workload'],
  exposure: WorldApp['exposure'],
  size: [ramMb: number, cpuM: number],
  on: Record<string, number>,
  port?: number,
];

const platform = (...row: Platform): WorldApp => {
  const [namespace, slug, name, category, workload, exposure, size, on, port] =
    row;
  return worldApp(
    CONTROL,
    undefined,
    slug,
    name,
    category,
    workload,
    exposure,
    size,
    on,
    { system: true, namespace, ...(port ? { port } : {}) },
  );
};

